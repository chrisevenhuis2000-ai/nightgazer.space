export function slugUit(pathname) {
  const m = /^\/nieuws\/([^/]+)/.exec(pathname)
  if (!m) return null
  try { return decodeURIComponent(m[1]).toLowerCase() } catch { return null }
}

export async function onRequest(context) {
  const res = await context.next()
  if (res.status !== 404) return res
  const slug = slugUit(new URL(context.request.url).pathname)
  if (!slug || !VERWIJDERD.has(slug)) return res
  return new Response(context.request.method === 'HEAD' ? null : HTML, {
    status: 410,
    headers: {
      'Content-Type': 'text/html; charset=utf-8',
      'X-Robots-Tag': 'noindex',
      'Cache-Control': 'public, max-age=3600',
    },
  })
}
