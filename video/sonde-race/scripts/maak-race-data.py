#!/usr/bin/env python3
"""Turn the JPL Horizons samples (assets/data/horizons-kwartaal.json) into assets/data/race-data.js.

Dates become decimal years; each probe gets a launch point at 1.0 AE so its row can enter the tower.
Run from video/sonde-race/:  python3 -I scripts/maak-race-data.py
"""
import datetime as dt
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = json.loads((ROOT / "assets/data/horizons-kwartaal.json").read_text())


def jaar(s: str) -> float:
    d = dt.date.fromisoformat(s)
    start = dt.date(d.year, 1, 1)
    return round(d.year + (d - start).days / ((dt.date(d.year + 1, 1, 1) - start).days), 4)


# id, Horizons key, display name, colour, launch date, last contact (None = still talking)
PROBES = [
    ("p10", "pioneer10", "PIONEER 10", "#F2994A", "1972-03-03", "2003-01-23"),
    ("p11", "pioneer11", "PIONEER 11", "#F2C94C", "1973-04-06", "1995-09-30"),
    ("v2", "voyager2", "VOYAGER 2", "#4F8FE8", "1977-08-20", None),
    ("v1", "voyager1", "VOYAGER 1", "#3DCFDF", "1977-09-05", None),
    ("nh", "newhorizons", "NEW HORIZONS", "#A77BF0", "2006-01-19", None),
]

out = {"bron": src["bron"], "probes": []}
for pid, key, naam, kleur, start, stil in PROBES:
    pts = [[jaar(d), au] for d, au in src[key]]
    pts.insert(0, [jaar(start), 1.0])
    out["probes"].append({"id": pid, "naam": naam, "kleur": kleur, "start": jaar(start),
                          "stil": jaar(stil) if stil else None, "au": pts})

(ROOT / "assets/data/race-data.js").write_text(
    "// Generated by scripts/maak-race-data.py from NASA/JPL Horizons. Do not edit by hand.\n"
    "window.__RACE = " + json.dumps(out, separators=(",", ":")) + ";\n")
print("ok", sum(len(p["au"]) for p in out["probes"]), "punten")
