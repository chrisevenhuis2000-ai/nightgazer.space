#!/usr/bin/env python3
"""Pick the active reel: writes actief.js and sets the durations + soundtrack in index.html.

  python3 -I scripts/kies.py maan                 # estimated timings (preview without voice-over)
  python3 -I scripts/kies.py maan out/maan/tijden.json   # measured timings from scripts/stem.py

tijden.json: {"lijnen": [[start, end], ...], "dur": seconds}
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GAP, START, OUTRO, CPS = 0.22, 0.35, 1.9, 13.5


def schatting(lijnen):
    t, out = START, []
    for l in lijnen:
        d = len(l["spreek"]) / CPS + 0.15
        out.append([round(t, 3), round(t + d, 3)])
        t += d + GAP
    return {"lijnen": out, "dur": round(out[-1][1] + OUTRO, 2)}


def main():
    rid = sys.argv[1]
    reel = json.loads((ROOT / "reels" / f"{rid}.json").read_text())
    tijden = json.loads(Path(sys.argv[2]).read_text()) if len(sys.argv) > 2 else schatting(reel["lijnen"])
    assert len(tijden["lijnen"]) == len(reel["lijnen"]), "aantal lijnen klopt niet"
    dur = round(round(tijden["dur"] * 30) / 30, 4)
    tijden["dur"] = dur
    (ROOT / "actief.js").write_text(
        "// Generated by scripts/kies.py. Do not edit.\n"
        f"window.__REEL_ID = {json.dumps(rid)};\n"
        f"window.__REEL = {json.dumps(reel, ensure_ascii=False)};\n"
        f"window.__TIJDEN = {json.dumps(tijden)};\n"
    )
    idx = ROOT / "index.html"
    html = idx.read_text()
    html = re.sub(r'data-duration="[0-9.]+"', f'data-duration="{dur}"', html)
    html = re.sub(r'<audio id="soundtrack" src="[^"]*"', f'<audio id="soundtrack" src="out/{rid}/master.wav"', html)
    idx.write_text(html)
    print(f"{rid}: {len(tijden['lijnen'])} lijnen, {dur} s")


main()
